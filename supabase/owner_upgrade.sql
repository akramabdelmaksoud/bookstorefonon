-- Owner upgrade: book details, suppliers + purchases, returns, discounts, expenses,
-- cash shifts, staff management and a single analytics function for the dashboard.
-- Safe to run once on top of schema.sql.

-- ---------- Columns ----------
alter table products
  add column if not exists author text,
  add column if not exists publisher text,
  add column if not exists shelf text,
  add column if not exists cover_url text,
  add column if not exists reorder_level integer not null default 5 check (reorder_level >= 0),
  add column if not exists active boolean not null default true;

alter table profiles add column if not exists active boolean not null default true;

alter table stock_logs drop constraint if exists stock_logs_change_type_check;
alter table stock_logs add constraint stock_logs_change_type_check
  check (change_type in ('sale','restock','manual_adjustment','return','purchase'));

-- ---------- New tables ----------
create table if not exists shifts (
  id uuid primary key default gen_random_uuid(),
  cashier_id uuid not null references auth.users(id),
  opened_at timestamptz not null default now(),
  opening_cash numeric(12,2) not null default 0 check (opening_cash >= 0),
  closed_at timestamptz,
  expected_cash numeric(12,2),
  counted_cash numeric(12,2),
  difference numeric(12,2),
  note text
);
create unique index if not exists one_open_shift_per_cashier on shifts(cashier_id) where closed_at is null;

alter table transactions
  add column if not exists subtotal numeric(12,2),
  add column if not exists discount numeric(12,2) not null default 0 check (discount >= 0),
  add column if not exists refunded_total numeric(12,2) not null default 0,
  add column if not exists shift_id uuid references shifts(id),
  add column if not exists receipt_no bigint generated by default as identity;

alter table transaction_items
  add column if not exists unit_cost numeric(12,2) not null default 0,
  add column if not exists refunded_qty integer not null default 0 check (refunded_qty >= 0);

create table if not exists suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  phone text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists purchases (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid references suppliers(id) on delete set null,
  total_cost numeric(12,2) not null default 0,
  note text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists purchase_items (
  id uuid primary key default gen_random_uuid(),
  purchase_id uuid not null references purchases(id) on delete cascade,
  product_id uuid not null references products(id),
  quantity integer not null check (quantity > 0),
  unit_cost numeric(12,2) not null check (unit_cost >= 0)
);

create table if not exists refunds (
  id uuid primary key default gen_random_uuid(),
  transaction_id uuid not null references transactions(id),
  payment_method text not null,
  total_refund numeric(12,2) not null default 0,
  reason text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists refund_items (
  id uuid primary key default gen_random_uuid(),
  refund_id uuid not null references refunds(id) on delete cascade,
  transaction_item_id uuid not null references transaction_items(id),
  product_id uuid not null references products(id),
  quantity integer not null check (quantity > 0),
  amount numeric(12,2) not null,
  unit_cost numeric(12,2) not null default 0
);

create table if not exists expenses (
  id uuid primary key default gen_random_uuid(),
  category text not null,
  amount numeric(12,2) not null check (amount > 0),
  note text,
  spent_on date not null default current_date,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists idx_products_active on products(active);
create index if not exists idx_purchase_items_p on purchase_items(purchase_id);
create index if not exists idx_purchases_created on purchases(created_at desc);
create index if not exists idx_refunds_created on refunds(created_at desc);
create index if not exists idx_refund_items_r on refund_items(refund_id);
create index if not exists idx_expenses_spent on expenses(spent_on desc);
create index if not exists idx_tx_shift on transactions(shift_id);
create index if not exists idx_shifts_cashier on shifts(cashier_id, opened_at desc);

