-- ---------- Selling (now with discount, cost snapshot, open shift) ----------
drop function if exists complete_sale(jsonb, text);
create or replace function complete_sale(p_items jsonb, p_payment_method text default 'cash', p_discount numeric default 0)
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_tx uuid;
  v_sub numeric(12,2) := 0;
  v_disc numeric(12,2) := round(coalesce(p_discount, 0), 2);
  v_item jsonb;
  v_prod products%rowtype;
  v_qty int;
  v_shift uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if not coalesce((select active from profiles where id = auth.uid()), false) then
    raise exception 'account disabled';
  end if;
  if p_payment_method not in ('cash','card') then raise exception 'bad payment method'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'empty cart'; end if;

  select id into v_shift from shifts where cashier_id = auth.uid() and closed_at is null;

  insert into transactions (cashier_id, total_amount, payment_method, shift_id)
  values (auth.uid(), 0, p_payment_method, v_shift) returning id into v_tx;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::int;
    if v_qty <= 0 then raise exception 'invalid quantity'; end if;

    select * into v_prod from products where id = (v_item->>'product_id')::uuid for update;
    if not found then raise exception 'product not found'; end if;
    if not v_prod.active then raise exception '% is no longer sold', v_prod.name; end if;
    if v_prod.stock_quantity < v_qty then
      raise exception 'insufficient stock for %', v_prod.name;
    end if;

    update products set stock_quantity = stock_quantity - v_qty where id = v_prod.id;

    insert into transaction_items (transaction_id, product_id, quantity, unit_price, total_price, unit_cost)
    values (v_tx, v_prod.id, v_qty, v_prod.selling_price, v_prod.selling_price * v_qty, v_prod.purchase_price);

    insert into stock_logs (product_id, change_type, quantity_changed, previous_stock, new_stock, reason, performed_by)
    values (v_prod.id, 'sale', -v_qty, v_prod.stock_quantity, v_prod.stock_quantity - v_qty,
            'Sale ' || v_tx, auth.uid());

    v_sub := v_sub + v_prod.selling_price * v_qty;
  end loop;

  if v_disc < 0 or v_disc > v_sub then raise exception 'invalid discount'; end if;
  update transactions set subtotal = v_sub, discount = v_disc, total_amount = v_sub - v_disc where id = v_tx;
  return v_tx;
end $$;

-- ---------- Returns / refunds (admin) ----------
-- p_items: [{"transaction_item_id": "...", "quantity": 1}]
create or replace function refund_sale(p_tx uuid, p_items jsonb, p_reason text default null)
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_tx transactions%rowtype;
  v_ref uuid;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_ti transaction_items%rowtype;
  v_prod products%rowtype;
  v_qty int;
  v_amt numeric(12,2);
begin
  if not is_admin() then raise exception 'admin only'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'nothing to refund'; end if;
  select * into v_tx from transactions where id = p_tx for update;
  if not found then raise exception 'sale not found'; end if;

  insert into refunds (transaction_id, payment_method, reason, created_by)
  values (p_tx, v_tx.payment_method, p_reason, auth.uid()) returning id into v_ref;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::int;
    select * into v_ti from transaction_items
      where id = (v_item->>'transaction_item_id')::uuid and transaction_id = p_tx for update;
    if not found then raise exception 'item not on this sale'; end if;
    if v_qty <= 0 or v_qty > v_ti.quantity - v_ti.refunded_qty then
      raise exception 'cannot refund more than was sold';
    end if;

    -- refund what the customer really paid for the item (after any discount)
    v_amt := round(v_ti.unit_price * v_qty *
             case when coalesce(v_tx.subtotal, 0) > 0 then v_tx.total_amount / v_tx.subtotal else 1 end, 2);

    update transaction_items set refunded_qty = refunded_qty + v_qty where id = v_ti.id;
    insert into refund_items (refund_id, transaction_item_id, product_id, quantity, amount, unit_cost)
    values (v_ref, v_ti.id, v_ti.product_id, v_qty, v_amt, v_ti.unit_cost);

    select * into v_prod from products where id = v_ti.product_id for update;
    update products set stock_quantity = stock_quantity + v_qty where id = v_prod.id;
    insert into stock_logs (product_id, change_type, quantity_changed, previous_stock, new_stock, reason, performed_by)
    values (v_prod.id, 'return', v_qty, v_prod.stock_quantity, v_prod.stock_quantity + v_qty,
            'Return on sale ' || p_tx, auth.uid());

    v_total := v_total + v_amt;
  end loop;

  update refunds set total_refund = v_total where id = v_ref;
  update transactions set refunded_total = refunded_total + v_total where id = p_tx;
  return v_ref;
end $$;

-- ---------- Purchases / receiving stock (admin) ----------
-- p_items: [{"product_id": "...", "quantity": 10, "unit_cost": 55.5}]
-- Purchase price becomes the weighted average of old stock and the new batch.
create or replace function receive_purchase(p_supplier uuid, p_items jsonb, p_note text default null)
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_prod products%rowtype;
  v_qty int;
  v_cost numeric(12,2);
  v_avg numeric(12,2);
begin
  if not is_admin() then raise exception 'admin only'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'empty purchase'; end if;

  insert into purchases (supplier_id, note, created_by) values (p_supplier, p_note, auth.uid())
  returning id into v_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::int;
    v_cost := (v_item->>'unit_cost')::numeric;
    if v_qty <= 0 or v_cost < 0 then raise exception 'invalid quantity or cost'; end if;

    select * into v_prod from products where id = (v_item->>'product_id')::uuid for update;
    if not found then raise exception 'product not found'; end if;

    v_avg := round((v_prod.stock_quantity * v_prod.purchase_price + v_qty * v_cost)
                   / (v_prod.stock_quantity + v_qty), 2);
    update products set stock_quantity = stock_quantity + v_qty, purchase_price = v_avg where id = v_prod.id;

    insert into purchase_items (purchase_id, product_id, quantity, unit_cost) values (v_id, v_prod.id, v_qty, v_cost);
    insert into stock_logs (product_id, change_type, quantity_changed, previous_stock, new_stock, reason, performed_by)
    values (v_prod.id, 'purchase', v_qty, v_prod.stock_quantity, v_prod.stock_quantity + v_qty,
            'Purchase ' || v_id, auth.uid());
    v_total := v_total + v_qty * v_cost;
  end loop;

  update purchases set total_cost = v_total where id = v_id;
  return v_id;
end $$;

-- ---------- Cash shifts ----------
create or replace function open_shift(p_opening numeric default 0)
returns uuid
language plpgsql security definer set search_path = public as $$
declare v_id uuid;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if exists (select 1 from shifts where cashier_id = auth.uid() and closed_at is null) then
    raise exception 'a shift is already open';
  end if;
  insert into shifts (cashier_id, opening_cash) values (auth.uid(), greatest(coalesce(p_opening, 0), 0))
  returning id into v_id;
  return v_id;
end $$;

create or replace function close_shift(p_counted numeric, p_note text default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  s shifts%rowtype;
  v_cash_sales numeric(12,2);
  v_cash_refunds numeric(12,2);
  v_expected numeric(12,2);
begin
  select * into s from shifts where cashier_id = auth.uid() and closed_at is null for update;
  if not found then raise exception 'no open shift'; end if;
  select coalesce(sum(total_amount), 0) into v_cash_sales from transactions
    where shift_id = s.id and payment_method = 'cash';
  select coalesce(sum(total_refund), 0) into v_cash_refunds from refunds
    where payment_method = 'cash' and created_at >= s.opened_at;
  v_expected := s.opening_cash + v_cash_sales - v_cash_refunds;
  update shifts set closed_at = now(), expected_cash = v_expected, counted_cash = p_counted,
                    difference = p_counted - v_expected, note = p_note
  where id = s.id;
  return jsonb_build_object('opening', s.opening_cash, 'cash_sales', v_cash_sales,
    'cash_refunds', v_cash_refunds, 'expected', v_expected, 'counted', p_counted,
    'difference', p_counted - v_expected);
end $$;

-- ---------- Staff management (admin) ----------
create or replace function create_staff(p_email text, p_password text, p_name text, p_role text default 'cashier')
returns uuid
language plpgsql security definer set search_path = public, extensions, auth as $$
declare
  v_id uuid := gen_random_uuid();
  v_email text := lower(trim(p_email));
begin
  if not is_admin() then raise exception 'admin only'; end if;
  if p_role not in ('cashier','admin') then raise exception 'bad role'; end if;
  if length(coalesce(p_password, '')) < 8 then raise exception 'password must be at least 8 characters'; end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'invalid email'; end if;
  if exists (select 1 from auth.users where lower(email) = v_email) then raise exception 'email already exists'; end if;

  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                          raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                          confirmation_token, recovery_token, email_change, email_change_token_new)
  values ('00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
          crypt(p_password, gen_salt('bf')), now(),
          '{"provider":"email","providers":["email"]}', jsonb_build_object('full_name', p_name), now(), now(), '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), v_id, v_id::text,
          jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true),
          'email', now(), now(), now());
  update profiles set role = p_role, full_name = coalesce(nullif(trim(p_name), ''), full_name) where id = v_id;
  return v_id;
end $$;

create or replace function list_staff()
returns table (id uuid, email text, full_name text, role text, active boolean, created_at timestamptz)
language plpgsql stable security definer set search_path = public, auth as $$
begin
  if not is_admin() then raise exception 'admin only'; end if;
  return query
    select p.id, u.email::text, p.full_name, p.role, p.active, p.created_at
    from profiles p join auth.users u on u.id = p.id order by p.created_at;
end $$;

create or replace function set_staff(p_id uuid, p_role text, p_active boolean)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'admin only'; end if;
  if p_role not in ('cashier','admin') then raise exception 'bad role'; end if;
  if p_id = auth.uid() and (p_role <> 'admin' or not p_active) then
    raise exception 'you cannot demote or disable yourself';
  end if;
  update profiles set role = p_role, active = p_active where id = p_id;
end $$;

-- ---------- Analytics ----------
-- Day boundaries use the shop's local time (Cairo).
create or replace function _period(p_from date, p_to date)
returns jsonb
language sql stable security definer set search_path = public as $$
  with b as (select (p_from::timestamp at time zone 'Africa/Cairo') lo,
                    ((p_to + 1)::timestamp at time zone 'Africa/Cairo') hi),
  s as (select count(*) n, coalesce(sum(total_amount), 0) sales, coalesce(sum(discount), 0) disc
        from transactions t, b where t.created_at >= b.lo and t.created_at < b.hi),
  c as (select coalesce(sum(i.unit_cost * i.quantity), 0) cogs
        from transaction_items i join transactions t on t.id = i.transaction_id, b
        where t.created_at >= b.lo and t.created_at < b.hi),
  r as (select coalesce(sum(total_refund), 0) refunds
        from refunds rf, b where rf.created_at >= b.lo and rf.created_at < b.hi),
  rc as (select coalesce(sum(ri.quantity * ri.unit_cost), 0) rcost
         from refund_items ri join refunds rf on rf.id = ri.refund_id, b
         where rf.created_at >= b.lo and rf.created_at < b.hi),
  e as (select coalesce(sum(amount), 0) exp from expenses where spent_on between p_from and p_to)
  select jsonb_build_object(
    'orders', s.n, 'sales', s.sales, 'discounts', s.disc, 'refunds', r.refunds,
    'revenue', s.sales - r.refunds,
    'cogs', c.cogs - rc.rcost,
    'gross_profit', s.sales - r.refunds - (c.cogs - rc.rcost),
    'expenses', e.exp,
    'net_profit', s.sales - r.refunds - (c.cogs - rc.rcost) - e.exp)
  from s, c, r, rc, e
$$;

create or replace function dashboard_stats(p_from date, p_to date)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_lo timestamptz := p_from::timestamp at time zone 'Africa/Cairo';
  v_hi timestamptz := (p_to + 1)::timestamp at time zone 'Africa/Cairo';
  v_days int := p_to - p_from + 1;
begin
  if not is_admin() then raise exception 'admin only'; end if;
  return jsonb_build_object(
    'current', _period(p_from, p_to),
    'previous', _period(p_from - v_days, p_from - 1),
    'series', (select coalesce(jsonb_agg(x order by x.day), '[]'::jsonb) from (
        select d::date::text as day,
               coalesce(s.sales, 0) - coalesce(r.refunds, 0) as revenue,
               coalesce(s.cnt, 0) as orders
        from generate_series(p_from, p_to, interval '1 day') d
        left join (select (created_at at time zone 'Africa/Cairo')::date dd, sum(total_amount) sales, count(*) cnt
                   from transactions where created_at >= v_lo and created_at < v_hi group by 1) s on s.dd = d::date
        left join (select (created_at at time zone 'Africa/Cairo')::date dd, sum(total_refund) refunds
                   from refunds where created_at >= v_lo and created_at < v_hi group by 1) r on r.dd = d::date
      ) x),
    'by_payment', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select payment_method as method, count(*) as orders, sum(total_amount) as total
        from transactions where created_at >= v_lo and created_at < v_hi group by 1 order by 3 desc) x),
    'by_cashier', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select coalesce(p.full_name, 'Staff') as name, count(*) as orders, sum(t.total_amount) as total
        from transactions t left join profiles p on p.id = t.cashier_id
        where t.created_at >= v_lo and t.created_at < v_hi group by 1 order by 3 desc) x),
    'top_products', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select p.name, p.author, sum(i.quantity) as qty, sum(i.total_price) as sales,
               sum(i.total_price - i.unit_cost * i.quantity) as profit
        from transaction_items i
        join transactions t on t.id = i.transaction_id
        join products p on p.id = i.product_id
        where t.created_at >= v_lo and t.created_at < v_hi
        group by p.id, p.name, p.author order by 3 desc, 4 desc limit 10) x),
    'reorder', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select p.id, p.name, p.author, p.stock_quantity as stock, p.reorder_level,
               coalesce(v.sold, 0) as sold_30d,
               greatest(p.reorder_level * 2 - p.stock_quantity,
                        ceil(coalesce(v.sold, 0) / 30.0 * 21)::int - p.stock_quantity, 1) as suggested
        from products p
        left join (select i.product_id, sum(i.quantity) sold
                   from transaction_items i join transactions t on t.id = i.transaction_id
                   where t.created_at >= now() - interval '30 days' group by 1) v on v.product_id = p.id
        where p.active and p.stock_quantity <= p.reorder_level
        order by p.stock_quantity, 2 limit 50) x),
    'dead_stock', (select coalesce(jsonb_agg(x), '[]'::jsonb) from (
        select p.name, p.author, p.stock_quantity as stock,
               p.stock_quantity * p.purchase_price as tied_up
        from products p
        where p.active and p.stock_quantity > 0 and p.created_at < now() - interval '60 days'
          and not exists (select 1 from transaction_items i join transactions t on t.id = i.transaction_id
                          where i.product_id = p.id and t.created_at >= now() - interval '60 days')
        order by 4 desc limit 20) x),
    'inventory', (select jsonb_build_object(
        'titles', count(*), 'units', coalesce(sum(stock_quantity), 0),
        'cost_value', coalesce(sum(stock_quantity * purchase_price), 0),
        'retail_value', coalesce(sum(stock_quantity * selling_price), 0))
        from products where active)
  );
end $$;

